  /*埋め込んだ疑似エフェクトを一時ファイルに書き出して適用*/
  function applyEffectControl(comp, layer) {
    var ffxFile = new File(Folder.temp.fsName + "/zabuton_effect_control.ffx");
    ffxFile.encoding = "BINARY";
    if (!ffxFile.open("w")) {
      alert("一時ファイルを作成できません: " + ffxFile.fsName);
      return false;
    }
    ffxFile.write(ZABUTON_FFX_BINARY);
    ffxFile.close();

    // applyPreset は選択中のレイヤーに適用されるため、対象レイヤーだけを選択する
    var selected = comp.selectedLayers;
    for (var i = 0; i < selected.length; i++) {
      selected[i].selected = false;
    }
    layer.selected = true;
    layer.applyPreset(ffxFile);
    ffxFile.remove();

    if (layer.property("ADBE Effect Parade").property(EFFECT_NAME) == null) {
      alert("エフェクトコントロール「" + EFFECT_NAME + "」を適用できませんでした。");
      return false;
    }
    return true;
  }

  function setDefaultValues(shape) {
    shape.effect(EFFECT_NAME)("Y_position_Padding").setValue(0);
  }

  /*文字のアンカーポイントを中心に持ってくるエクスプレッション*/
  function setAnchorPointToCenter(layer) {
    layer
      .property("ADBE Transform Group")
      .property("ADBE Anchor Point").expression =
      "var r = thisLayer.sourceRectAtTime(time, false);\n" +
      "[r.left + r.width / 2, r.top + r.height / 2];";
  }

  /*座布団の位置を親（テキスト）の中心に合わせる*/
  function setShapePositionExpression(shape) {
    shape
      .property("ADBE Transform Group")
      .property("ADBE Position").expression = "parent.transform.anchorPoint;";
  }

  /*シェイプへのエクスプレッションの設定（サイズ）*/
  function setShapeSizeExpression(shape) {
    shape
      .property("ADBE Root Vectors Group")
      .addProperty("ADBE Vector Shape - Rect")
      .property("ADBE Vector Rect Size").expression =
      "var fx = effect('" + EFFECT_NAME + "');\n" +
      "var r = parent.sourceRectAtTime(time, false);\n" +
      "[r.width + fx('X_position_Padding'), r.height + fx('Y_position_Padding')];";
  }

  /*シェイプへのエクスプレッションの設定（角丸）*/
  function setShapeRoundnessExpression(shape) {
    shape
      .property("ADBE Root Vectors Group")
      .property("ADBE Vector Shape - Rect")
      .property("ADBE Vector Rect Roundness").expression =
      "effect('" + EFFECT_NAME + "')('zabuton_radius');";
  }

  /*シェイプへのエクスプレッションの設定（塗り）*/
  function setFillColor(shape) {
    shape
      .property("ADBE Root Vectors Group")
      .addProperty("ADBE Vector Graphic - Fill")
      .property("ADBE Vector Fill Color").expression =
      "effect('" + EFFECT_NAME + "')('BG_Color');";
  }
